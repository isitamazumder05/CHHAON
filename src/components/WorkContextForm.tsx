import React, { useState } from 'react';
import {
  SlidersHorizontal,
  Flame,
  Clock,
  Umbrella,
  Droplets,
  HeartPulse,
  Check,
  ChevronLeft,
  ChevronRight,
  ArrowRight,
  Activity,
  Edit3,
} from 'lucide-react';
import type {
  WorkContext,
  WorkIntensity,
  ExposureDuration,
  ShadeAvailability,
  WaterAvailability,
  AcclimatizationStatus,
  AssessmentResult,
} from '../types';

interface WorkContextFormProps {
  context: WorkContext;
  onChange: (updated: WorkContext) => void;
  assessment?: AssessmentResult | null;
  onReviewAssessment?: () => void;
}

type StepNumber = 1 | 2 | 3 | 4 | 5;

interface StepInfo {
  num: StepNumber;
  id: keyof WorkContext;
  title: string;
  shortLabel: string;
  progressLabelCompact?: string;
  progressLabelWide?: string;
  icon: React.ElementType;
  helper: string;
}

const STEPS: StepInfo[] = [
  {
    num: 1,
    id: 'intensity',
    title: 'Workload (Physical Exertion)',
    shortLabel: 'Workload',
    icon: Flame,
    helper: 'Internal metabolic heat generated by physical labor (~150 W to >350 W).',
  },
  {
    num: 2,
    id: 'duration',
    title: 'Exposure Duration',
    shortLabel: 'Duration',
    icon: Clock,
    helper: 'Cumulative outdoor shift length; extended shifts (≥ 6h) trigger mandatory electrolytes.',
  },
  {
    num: 3,
    id: 'shade',
    title: 'Overhead Canopy Shade',
    shortLabel: 'Shade',
    icon: Umbrella,
    helper: 'Direct radiant sunlight adds an estimated ~3°C–5°C heat load over shaded air.',
  },
  {
    num: 4,
    id: 'water',
    title: 'Potable Water Access',
    shortLabel: 'Water',
    icon: Droplets,
    helper: 'Drinking ~1 cup every 15–20 min protects against rapid core thermal strain.',
  },
  {
    num: 5,
    id: 'acclimatization',
    title: 'Crew Heat Adaptation',
    shortLabel: 'Heat Adaptation',
    progressLabelCompact: 'Heat Adaptation',
    progressLabelWide: 'Heat Adaptation',
    icon: HeartPulse,
    helper: 'Physiological heat adaptation (acclimatization, 7–14 days) conditions sweating and cardiovascular stamina.',
  },
];

export const WorkContextForm: React.FC<WorkContextFormProps> = ({
  context,
  onChange,
  assessment,
  onReviewAssessment,
}) => {
  const [activeStep, setActiveStep] = useState<StepNumber>(1);

  const handleIntensityChange = (intensity: WorkIntensity) => {
    onChange({ ...context, intensity });
  };

  const handleDurationChange = (duration: ExposureDuration) => {
    onChange({ ...context, duration });
  };

  const handleShadeChange = (shade: ShadeAvailability) => {
    onChange({ ...context, shade });
  };

  const handleWaterChange = (water: WaterAvailability) => {
    onChange({ ...context, water });
  };

  const handleAcclimatizationChange = (acclimatization: AcclimatizationStatus) => {
    onChange({ ...context, acclimatization });
  };

  const goToStep = (step: StepNumber) => {
    setActiveStep(step);
  };

  const nextStep = () => {
    if (activeStep < 5) {
      setActiveStep((prev) => (prev + 1) as StepNumber);
    } else if (onReviewAssessment) {
      onReviewAssessment();
    }
  };

  const prevStep = () => {
    if (activeStep > 1) {
      setActiveStep((prev) => (prev - 1) as StepNumber);
    }
  };

  const currentStepInfo = STEPS[activeStep - 1];

  // Helper labels for the compact summary chips
  const getSummaryLabel = (step: StepNumber): string => {
    switch (step) {
      case 1:
        return context.intensity === 'light'
          ? 'Light (~175W)'
          : context.intensity === 'heavy'
          ? 'Heavy (>350W)'
          : 'Moderate (275W)';
      case 2:
        return `${context.duration} shift`;
      case 3:
        return context.shade === 'none'
          ? 'Direct Sun'
          : context.shade === 'partial'
          ? 'Partial Shade'
          : 'Ample Canopy';
      case 4:
        return context.water === 'abundant'
          ? '< 25m'
          : context.water === 'limited'
          ? '25–100m'
          : 'Scarce (>100m)';
      case 5:
        return context.acclimatization === 'acclimatized'
          ? 'Fully Adapted (>14d)'
          : context.acclimatization === 'partial'
          ? 'Partially Adapted (3–6d)'
          : context.acclimatization === 'unacclimatized'
          ? 'Unadapted (New Crew)'
          : 'Unknown Status';
    }
  };

  return (
    <section className="chhaon-card worksite-setup-card" aria-labelledby="worksite-setup-heading">
      {/* Header */}
      <div className="card-header">
        <div className="card-title-group">
          <span className="card-title-icon" aria-hidden="true">
            <SlidersHorizontal size={20} />
          </span>
          <h2 id="worksite-setup-heading" className="card-title">
            Worksite Setup
          </h2>
        </div>
        <span className="card-badge">Step {activeStep} of 5</span>
      </div>

      {/* Progress Indicator: Stepper Bar */}
      <div className="stepper-progress-wrapper" role="region" aria-label="Setup step navigation">
        <div className="stepper-track-bar">
          <div
            className="stepper-fill-bar"
            style={{ width: `${(activeStep / 5) * 100}%` }}
            aria-hidden="true"
          />
        </div>

        <div className="stepper-tabs-row" role="tablist" aria-label="Worksite Setup Steps">
          {STEPS.map((s) => {
            const isCurrent = activeStep === s.num;
            const isCompleted = activeStep > s.num;
            const progressCompact = s.progressLabelCompact || s.shortLabel;
            const progressWide = s.progressLabelWide || s.shortLabel;

            return (
              <button
                key={s.num}
                type="button"
                className={`stepper-tab-btn ${isCurrent ? 'active' : ''} ${isCompleted ? 'completed' : ''}`}
                onClick={() => goToStep(s.num)}
                role="tab"
                aria-selected={isCurrent}
                aria-label={`Step ${s.num}: ${progressCompact}`}
                title={`Jump to Step ${s.num}: ${s.title}`}
              >
                <span className="tab-num-badge">
                  {isCompleted ? <Check size={11} aria-hidden="true" /> : s.num}
                </span>
                <span className="tab-label-text">
                  {s.progressLabelCompact ? (
                    <>
                      <span className="label-wide">{progressWide}</span>
                      <span className="label-compact">{progressCompact}</span>
                    </>
                  ) : (
                    s.shortLabel
                  )}
                </span>
              </button>
            );
          })}
        </div>
      </div>

      {/* Completed Settings Summary Chips (Editable jump shortcuts) */}
      <div className="completed-summary-bar" aria-label="Configured worksite settings">
        <div className="summary-chips-label">
          <span>Active Configuration:</span>
        </div>
        <div className="summary-chips-list">
          {STEPS.map((s) => {
            const isEditing = activeStep === s.num;
            return (
              <button
                key={s.num}
                type="button"
                className={`compact-summary-chip ${isEditing ? 'editing-active' : ''}`}
                onClick={() => goToStep(s.num)}
                title={`Click to edit ${s.shortLabel} (currently ${getSummaryLabel(s.num)})`}
                aria-label={`Edit ${s.shortLabel}`}
              >
                <span className="chip-key">{s.shortLabel}:</span>
                <span className="chip-val">{getSummaryLabel(s.num)}</span>
                <Edit3 size={10} className="chip-edit-icon" aria-hidden="true" />
              </button>
            );
          })}
        </div>
      </div>

      {/* Core Setup Grid: Active Step Editor (Left/Top) + Live Worksite Snapshot (Right/Bottom) */}
      <div className="setup-main-grid">
        {/* Active Step Section */}
        <div className="active-step-panel">
          <div className="active-step-header">
            <div className="step-title-row">
              <span className="step-icon-badge" aria-hidden="true">
                <currentStepInfo.icon size={16} />
              </span>
              <h3 className="active-step-title">
                {activeStep}. {currentStepInfo.title}
              </h3>
            </div>
            <p className="active-step-helper">{currentStepInfo.helper}</p>
          </div>

          <div className="active-options-container" role="radiogroup" aria-labelledby="active-step-title">
            {/* Step 1: Workload */}
            {activeStep === 1 && (
              <div className="step-options-vertical">
                {[
                  {
                    id: 'light' as WorkIntensity,
                    title: 'Light Exertion',
                    detail: '150–200 W',
                    sub: 'Supervision, operating machine cab, surveying',
                  },
                  {
                    id: 'moderate' as WorkIntensity,
                    title: 'Moderate Labor',
                    detail: '200–350 W',
                    sub: 'Bricklaying, plastering, carpentry, plumbing',
                  },
                  {
                    id: 'heavy' as WorkIntensity,
                    title: 'Heavy Physical Labor',
                    detail: '> 350 W',
                    sub: 'Concrete hauling, manual excavation, roofing',
                  },
                ].map((opt) => {
                  const isSelected = context.intensity === opt.id;
                  return (
                    <button
                      key={opt.id}
                      type="button"
                      className={`step-option-card ${isSelected ? 'selected-terracotta' : ''}`}
                      onClick={() => handleIntensityChange(opt.id)}
                      role="radio"
                      aria-checked={isSelected}
                    >
                      <div className="option-card-main">
                        <div className="option-card-header">
                          <strong className="option-title">{opt.title}</strong>
                          <span className="option-detail-badge">{opt.detail}</span>
                        </div>
                        <p className="option-sub">{opt.sub}</p>
                      </div>
                      <div className="option-select-indicator">
                        {isSelected && <Check size={14} className="check-icon" aria-hidden="true" />}
                      </div>
                    </button>
                  );
                })}
              </div>
            )}

            {/* Step 2: Duration */}
            {activeStep === 2 && (
              <div className="step-options-duration-grid">
                {[
                  { id: '1h' as ExposureDuration, label: '1 Hour', sub: 'Short task / inspection' },
                  { id: '2h' as ExposureDuration, label: '2 Hours', sub: 'Brief stretch' },
                  { id: '4h' as ExposureDuration, label: '4 Hours', sub: 'Half workday stretch' },
                  { id: '6h' as ExposureDuration, label: '6 Hours', sub: 'Extended (electrolytes)' },
                  { id: '8h+' as ExposureDuration, label: '8+ Hours', sub: 'Full day continuous labor' },
                ].map((dur) => {
                  const isSelected = context.duration === dur.id;
                  return (
                    <button
                      key={dur.id}
                      type="button"
                      className={`duration-step-btn ${isSelected ? 'selected-terracotta' : ''}`}
                      onClick={() => handleDurationChange(dur.id)}
                      role="radio"
                      aria-checked={isSelected}
                    >
                      <span className="dur-btn-label">{dur.label}</span>
                      <span className="dur-btn-sub">{dur.sub}</span>
                      {isSelected && <span className="dur-active-dot" aria-hidden="true" />}
                    </button>
                  );
                })}
              </div>
            )}

            {/* Step 3: Shade */}
            {activeStep === 3 && (
              <div className="step-options-vertical">
                {[
                  {
                    id: 'none' as ShadeAvailability,
                    title: 'Direct Sunlight (None)',
                    detail: '+3°C to 5°C Radiant Heat',
                    sub: 'Full open sky, direct solar heating on tools and bodies',
                  },
                  {
                    id: 'partial' as ShadeAvailability,
                    title: 'Partial / Intermittent',
                    detail: '+1°C to 2°C Heat Load',
                    sub: 'Scattered tree cover or periodic canopy rotation',
                  },
                  {
                    id: 'ample' as ShadeAvailability,
                    title: 'Ample Canopy Shelter',
                    detail: '0°C Radiant Burden',
                    sub: 'Continuous shamiana / tarpaulin shelter, shaded pauses',
                  },
                ].map((opt) => {
                  const isSelected = context.shade === opt.id;
                  return (
                    <button
                      key={opt.id}
                      type="button"
                      className={`step-option-card ${isSelected ? 'selected-terracotta' : ''}`}
                      onClick={() => handleShadeChange(opt.id)}
                      role="radio"
                      aria-checked={isSelected}
                    >
                      <div className="option-card-main">
                        <div className="option-card-header">
                          <strong className="option-title">{opt.title}</strong>
                          <span className="option-detail-badge">{opt.detail}</span>
                        </div>
                        <p className="option-sub">{opt.sub}</p>
                      </div>
                      <div className="option-select-indicator">
                        {isSelected && <Check size={14} className="check-icon" aria-hidden="true" />}
                      </div>
                    </button>
                  );
                })}
              </div>
            )}

            {/* Step 4: Water */}
            {activeStep === 4 && (
              <div className="step-options-vertical">
                {[
                  {
                    id: 'abundant' as WaterAvailability,
                    title: 'Abundant & Nearby',
                    detail: '< 25 Meters',
                    sub: 'Continuous cool potable water stationed on-site',
                  },
                  {
                    id: 'limited' as WaterAvailability,
                    title: 'Limited / Periodic',
                    detail: '25–100 Meters',
                    sub: 'Refilled during scheduled breaks only',
                  },
                  {
                    id: 'scarce' as WaterAvailability,
                    title: 'Scarce / Remote',
                    detail: '> 100 Meters (Critical)',
                    sub: 'Remote water access; critical dehydration hazard',
                  },
                ].map((opt) => {
                  const isSelected = context.water === opt.id;
                  return (
                    <button
                      key={opt.id}
                      type="button"
                      className={`step-option-card ${isSelected ? 'selected-terracotta' : ''}`}
                      onClick={() => handleWaterChange(opt.id)}
                      role="radio"
                      aria-checked={isSelected}
                    >
                      <div className="option-card-main">
                        <div className="option-card-header">
                          <strong className="option-title">{opt.title}</strong>
                          <span className="option-detail-badge">{opt.detail}</span>
                        </div>
                        <p className="option-sub">{opt.sub}</p>
                      </div>
                      <div className="option-select-indicator">
                        {isSelected && <Check size={14} className="check-icon" aria-hidden="true" />}
                      </div>
                    </button>
                  );
                })}
              </div>
            )}

            {/* Step 5: Heat Adaptation */}
            {activeStep === 5 && (
              <div className="step-options-vertical">
                {[
                  {
                    id: 'acclimatized' as AcclimatizationStatus,
                    title: 'Fully Adapted (Acclimatized)',
                    detail: '> 14 Days on Site',
                    sub: 'Conditioned sweat mechanisms active; stable endurance',
                  },
                  {
                    id: 'partial' as AcclimatizationStatus,
                    title: 'Partially Adapted',
                    detail: '3–6 Days Exposure',
                    sub: 'Cardiovascular adaptations underway; fatigue sets in early',
                  },
                  {
                    id: 'unacclimatized' as AcclimatizationStatus,
                    title: 'Unadapted (New Crew)',
                    detail: 'High Strain Risk',
                    sub: 'New workers or returned from leave; gradual pacing required',
                  },
                  {
                    id: 'unknown' as AcclimatizationStatus,
                    title: 'Unknown Adaptation Status',
                    detail: 'Precaution Buffer',
                    sub: 'Safety protocol applies conservative precaution margin',
                  },
                ].map((opt) => {
                  const isSelected = context.acclimatization === opt.id;
                  return (
                    <button
                      key={opt.id}
                      type="button"
                      className={`step-option-card ${isSelected ? 'selected-terracotta' : ''}`}
                      onClick={() => handleAcclimatizationChange(opt.id)}
                      role="radio"
                      aria-checked={isSelected}
                    >
                      <div className="option-card-main">
                        <div className="option-card-header">
                          <strong className="option-title">{opt.title}</strong>
                          <span className="option-detail-badge">{opt.detail}</span>
                        </div>
                        <p className="option-sub">{opt.sub}</p>
                      </div>
                      <div className="option-select-indicator">
                        {isSelected && <Check size={14} className="check-icon" aria-hidden="true" />}
                      </div>
                    </button>
                  );
                })}
              </div>
            )}
          </div>

          {/* Stepper Navigation Buttons */}
          <div className="step-navigation-bar">
            <button
              type="button"
              className="step-nav-btn btn-prev"
              onClick={prevStep}
              disabled={activeStep === 1}
              aria-label="Previous step"
            >
              <ChevronLeft size={15} aria-hidden="true" />
              <span>Previous</span>
            </button>

            {activeStep < 5 ? (
              <button
                type="button"
                className="step-nav-btn btn-next"
                onClick={nextStep}
                aria-label={`Next step: ${STEPS[activeStep].shortLabel}`}
              >
                <span>Next ({STEPS[activeStep].shortLabel})</span>
                <ChevronRight size={15} aria-hidden="true" />
              </button>
            ) : (
              <button
                type="button"
                className="step-nav-btn btn-review"
                onClick={onReviewAssessment}
                aria-label="Review live assessment results"
              >
                <span>Review Assessment</span>
                <ArrowRight size={15} aria-hidden="true" />
              </button>
            )}
          </div>
        </div>

        {/* Live Worksite Snapshot (Beside active step on desktop, stacked below on mobile) */}
        <aside className="worksite-snapshot-panel" aria-label="Live Worksite Snapshot">
          <div className="snapshot-card-header">
            <div className="snapshot-title-group">
              <Activity size={15} className="snapshot-icon" aria-hidden="true" />
              <h4 className="snapshot-title">Live Worksite Snapshot</h4>
            </div>
            <span className="snapshot-live-tag">LIVE</span>
          </div>

          <div className="snapshot-metrics-stack">
            {/* 1. Metabolic Heat */}
            <div className="snapshot-metric-row">
              <span className="snapshot-metric-label">Metabolic Heat:</span>
              <span className="snapshot-metric-value">
                {context.intensity === 'heavy'
                  ? '> 350 W (Heavy)'
                  : context.intensity === 'moderate'
                  ? '200–350 W (Moderate)'
                  : '150–200 W (Light)'}
              </span>
            </div>

            {/* 2. Shift Exposure */}
            <div className="snapshot-metric-row">
              <span className="snapshot-metric-label">Shift Duration:</span>
              <span className="snapshot-metric-value">
                {context.duration} {context.duration === '6h' || context.duration === '8h+' ? '(Electrolytes)' : ''}
              </span>
            </div>

            {/* 3. Solar Radiant Heat */}
            <div className="snapshot-metric-row">
              <span className="snapshot-metric-label">Solar Radiant Load:</span>
              <span className="snapshot-metric-value">
                {context.shade === 'none'
                  ? '+3°C to 5°C Sun'
                  : context.shade === 'partial'
                  ? '+1°C to 2°C Shade'
                  : '0°C Sheltered'}
              </span>
            </div>

            {/* 4. Hydration Proximity */}
            <div className="snapshot-metric-row">
              <span className="snapshot-metric-label">Water Proximity:</span>
              <span className="snapshot-metric-value">
                {context.water === 'abundant'
                  ? '< 25m (Optimal)'
                  : context.water === 'limited'
                  ? '25–100m'
                  : '> 100m (Critical)'}
              </span>
            </div>

            {/* 5. Crew Heat Adaptation */}
            <div className="snapshot-metric-row">
              <span className="snapshot-metric-label">Heat Adaptation:</span>
              <span className="snapshot-metric-value">
                {context.acclimatization === 'acclimatized'
                  ? 'Fully Adapted'
                  : context.acclimatization === 'partial'
                  ? 'Partially Adapted'
                  : context.acclimatization === 'unacclimatized'
                  ? 'Unadapted'
                  : 'Precaution Buffer'}
              </span>
            </div>

            {/* Live Screening Status if available */}
            {assessment && (
              <div className="snapshot-screening-box" data-tier={assessment.tier}>
                <span className="screening-box-label">Live Screening Tier:</span>
                <span className="screening-box-val">{assessment.tierLabel}</span>
                <span className="screening-box-hi">Felt HI ~{assessment.heatIndex}°C</span>
              </div>
            )}
          </div>

          {/* Review Assessment Action */}
          {onReviewAssessment && (
            <button
              type="button"
              className="snapshot-review-action"
              onClick={onReviewAssessment}
              aria-label="View live assessment details"
            >
              <span>Review Assessment</span>
              <ArrowRight size={13} aria-hidden="true" />
            </button>
          )}
        </aside>
      </div>
    </section>
  );
};
